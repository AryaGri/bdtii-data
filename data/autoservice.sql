DROP TABLE IF EXISTS repairs, cars, mechanics, clients CASCADE;

CREATE TABLE clients (id SERIAL PRIMARY KEY, name VARCHAR(100) NOT NULL, phone VARCHAR(20), city VARCHAR(50));
CREATE TABLE cars (id SERIAL PRIMARY KEY, client_id INT NOT NULL REFERENCES clients(id), brand VARCHAR(50), year INT);
CREATE TABLE mechanics (id SERIAL PRIMARY KEY, name VARCHAR(100) NOT NULL, specialization VARCHAR(50));
CREATE TABLE repairs (id SERIAL PRIMARY KEY, car_id INT NOT NULL REFERENCES cars(id), mechanic_id INT NOT NULL REFERENCES mechanics(id), repair_date DATE NOT NULL, cost NUMERIC(10,2) NOT NULL);

