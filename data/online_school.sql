DROP TABLE IF EXISTS payments, enrollments, courses, teachers, students CASCADE;

CREATE TABLE teachers (id SERIAL PRIMARY KEY, name VARCHAR(100) NOT NULL, subject VARCHAR(50));
CREATE TABLE courses (id SERIAL PRIMARY KEY, title VARCHAR(100) NOT NULL, category VARCHAR(50), teacher_id INT REFERENCES teachers(id), price NUMERIC(10,2));
CREATE TABLE students (id SERIAL PRIMARY KEY, name VARCHAR(100) NOT NULL, grade INT, school VARCHAR(50), reg_date DATE);
CREATE TABLE enrollments (id SERIAL PRIMARY KEY, student_id INT NOT NULL REFERENCES students(id), course_id INT NOT NULL REFERENCES courses(id), enroll_date DATE NOT NULL, status VARCHAR(10) CHECK (status IN ('active','finished','dropped')));
CREATE TABLE payments (id SERIAL PRIMARY KEY, enrollment_id INT NOT NULL REFERENCES enrollments(id), pay_date DATE NOT NULL, amount NUMERIC(10,2) NOT NULL);

